/** Uses the checked-in v5 schema, not tables generated by the current Room implementation. */
@RunWith(AndroidJUnit4::class)
class StatefulMigrationTest {
    @Test fun version5HistoryQueueBatchesAndReplacementsSurviveMigrationAndReopen() = runBlocking {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val name = "stateful-migration-${UUID.randomUUID()}.db"
        val settings = JSONObject(ConversionDefaults(autoSave = true).encode()).apply {
            remove("heicGainmapCompatibility")
            remove("avifGainmapCompatibility")
        }.toString()
        val batches = listOf(
            BatchEntity("active-batch", "[\"pending\",\"saved\",\"active\",\"probing\"]", settings, createdAt = 100),
            BatchEntity("cancelled-batch", "[\"failed\"]", settings, cancelled = true, createdAt = 200),
        )
        val history = listOf("PENDING", "SAVED", "FAILED").mapIndexed { index, state ->
            val taskId = state.lowercase()
            HistoryEntity(id = (index + 1).toLong(), displayName = "$taskId.heic",
                inputUri = "content://migration-fixture/source/$taskId",
                outputUri = if (state == "SAVED") "content://migration-fixture/output/$taskId"
                    else "${context.filesDir}/migration-fixture/$taskId.heic",
                inputBytes = 2048 + index.toLong(), outputBytes = 1024 + index.toLong(),
                width = 64, height = 48, gainmapWidth = 16, gainmapHeight = 12,
                hadGainMap = true, format = "HEIC", inputFormat = "JPEG", durationMs = 12.5,
                maxContentBoost = 4f, createdAt = 1000 + index.toLong(), status = "DONE", taskId = taskId,
                batchId = if (state == "FAILED") "cancelled-batch" else "active-batch", saveState = state,
                settingsSummary = "q90 · fixture $state", hasExif = true)
        }
        val probe = ProbeResult(0, "", true, 0, 64, 48, 16, 12, true, 4f, 4f)
        val tasks = history.map { row ->
            QueueItem(row.taskId!!, row.inputUri, row.displayName, row.inputBytes, probe = probe,
                status = QueueStatus.DONE, progress = 100,
                result = TranscodeResult(0, "", true, 64, 48, 16, 12, row.inputBytes, row.outputBytes,
                    12.5, hasGainMap = true, hasExif = true, maxContentBoost = 4f),
                outputUri = row.outputUri, historyId = row.id, createdAt = row.createdAt,
                batchId = row.batchId, error = if (row.saveState == "FAILED") "保存失败，可重试" else null)
        } + listOf(
            QueueItem("active", "content://migration-fixture/source/active", "active.jpg", 4096,
                probe = probe, status = QueueStatus.CONVERTING, progress = 35, createdAt = 2000, batchId = "active-batch"),
            QueueItem("probing", "content://migration-fixture/source/probing", "probing.jpg", 4096,
                status = QueueStatus.PROBING, createdAt = 2001, batchId = "active-batch"),
        )
        val replacements = history.mapIndexed { index, row ->
            ReplacementEntity(row.id, row.batchId, row.inputUri, row.outputUri,
                "source-hash-${row.id}", "output-hash-${row.id}",
                listOf("PREPARED", "READY", "REQUESTED")[index], "fixture note ${row.id}")
        }
        var db: AppDatabase? = null
        var scope: CoroutineScope? = null
        try {
            createVersion5(context, name).use { old ->
                old.beginTransaction()
                try {
                    batches.forEach { old.insertOrThrow("batches", null, values(
                        "id" to it.id, "itemIds" to it.itemIds, "settings" to it.settings,
                        "cancelled" to it.cancelled, "createdAt" to it.createdAt)) }
                    history.forEach { old.insertOrThrow("history", null, historyValues(it)) }
                    tasks.forEach { old.insertOrThrow("tasks", null, taskValues(it)) }
                    // Older completed tasks can predate the three result metadata fields.
                    old.execSQL("UPDATE tasks SET result_hasGainMap = NULL, result_hasExif = NULL, " +
                        "result_maxContentBoost = NULL WHERE id = ?", arrayOf("pending"))
                    replacements.forEach { old.insertOrThrow("replacements", null, values(
                        "historyId" to it.historyId, "batchId" to it.batchId, "sourceUri" to it.sourceUri,
                        "outputUri" to it.outputUri, "sourceHash" to it.sourceHash, "outputHash" to it.outputHash,
                        "state" to it.state, "note" to it.note)) }
                    old.setTransactionSuccessful()
                } finally { old.endTransaction() }
            }
            val migrated = open(context, name).also { db = it }
            assertEquals(7, migrated.openHelper.writableDatabase.version)
            assertContent(migrated, history, batches, replacements)
            assertEquals(tasks, migrated.taskDao().all())
            migrated.openHelper.readableDatabase.query("PRAGMA index_list(history)").use { cursor ->
                val names = mutableSetOf<String>()
                while (cursor.moveToNext()) names += cursor.getString(cursor.getColumnIndexOrThrow("name"))
                assertTrue("v6 publication index exists", "index_history_saveState_createdAt" in names)
            }
            val workerScope = CoroutineScope(SupervisorJob() + Dispatchers.IO).also { scope = it }
            val repo = ConversionRepository(migrated.taskDao(), workerScope)
            repo.awaitReady()
            repo.flush()
            val recovered = repo.queue.value
            assertEquals(QueueStatus.READY, repo.find("active")?.status)
            assertEquals(35, repo.find("active")?.progress)
            assertTrue(repo.find("active")!!.error!!.contains("中断"))
            assertEquals(QueueStatus.READY, repo.find("probing")?.status)
            assertNull(repo.find("probing")?.probe)
            assertNull(repo.find("probing")?.result)
            assertEquals(tasks.take(3), recovered.take(3))
            workerScope.coroutineContext[Job]!!.cancelAndJoin()
            scope = null
            migrated.close()
            db = null

            val reopened = open(context, name).also { db = it }
            assertContent(reopened, history, batches, replacements)
            assertEquals(recovered, reopened.taskDao().all())
            assertEquals(listOf(1L), reopened.historyDao()
                .pendingPublicationPage(listOf("active-batch"), Long.MIN_VALUE, Long.MIN_VALUE, 32).map { it.id })
            assertFalse(decodeDefaults(reopened.taskDao().batch("active-batch")!!.settings).heicGainmapCompatibility)
            assertFalse(decodeDefaults(reopened.taskDao().batch("active-batch")!!.settings).avifGainmapCompatibility)
        } finally {
            scope?.coroutineContext?.get(Job)?.cancelAndJoin()
            db?.close()
            context.deleteDatabase(name)
        }
    }

    private fun open(context: Context, name: String) = Room.databaseBuilder(context, AppDatabase::class.java, name)
        .addMigrations(AppDatabase.MIGRATION_5_6, AppDatabase.MIGRATION_6_7).build()

    private fun createVersion5(context: Context, name: String): SQLiteDatabase {
        val json = InstrumentationRegistry.getInstrumentation().context.assets
            .open("app.ultraslim.data.AppDatabase/5.json").bufferedReader().use { JSONObject(it.readText()) }
            .getJSONObject("database")
        val db = context.openOrCreateDatabase(name, 0, null)
        try {
            val entities = json.getJSONArray("entities")
            for (index in 0 until entities.length()) {
                val entity = entities.getJSONObject(index)
                val table = entity.getString("tableName")
                db.execSQL(entity.getString("createSql").replace("\${TABLE_NAME}", table))
                entity.optJSONArray("indices")?.let { indices ->
                    for (entry in 0 until indices.length()) db.execSQL(indices.getJSONObject(entry)
                        .getString("createSql").replace("\${TABLE_NAME}", table))
                }
            }
            val setup = json.getJSONArray("setupQueries")
            for (index in 0 until setup.length()) db.execSQL(setup.getString(index))
            db.version = json.getInt("version")
            return db
        } catch (error: Exception) { db.close(); throw error }
    }

    private suspend fun assertContent(db: AppDatabase, history: List<HistoryEntity>,
        batches: List<BatchEntity>, replacements: List<ReplacementEntity>) {
        assertEquals(history, db.historyDao().all().sortedBy { it.id })
        history.forEach { assertEquals(it, db.historyDao().byTask(it.taskId!!)) }
        batches.forEach { assertEquals(it, db.taskDao().batch(it.id)) }
        replacements.forEach { assertEquals(it, db.replacementDao().byId(it.historyId)) }
    }

    private fun historyValues(row: HistoryEntity) = values(
        "id" to row.id, "displayName" to row.displayName, "inputUri" to row.inputUri,
        "outputUri" to row.outputUri, "inputBytes" to row.inputBytes, "outputBytes" to row.outputBytes,
        "width" to row.width, "height" to row.height, "gainmapWidth" to row.gainmapWidth,
        "gainmapHeight" to row.gainmapHeight, "hadGainMap" to row.hadGainMap, "format" to row.format,
        "inputFormat" to row.inputFormat, "durationMs" to row.durationMs, "maxContentBoost" to row.maxContentBoost,
        "createdAt" to row.createdAt, "status" to row.status, "taskId" to row.taskId, "batchId" to row.batchId,
        "saveState" to row.saveState, "settingsSummary" to row.settingsSummary, "hasExif" to row.hasExif)

    private fun taskValues(row: QueueItem) = values(
        "id" to row.id, "uri" to row.uri, "displayName" to row.displayName, "sizeBytes" to row.sizeBytes,
        "status" to row.status.name, "progress" to row.progress, "outputUri" to row.outputUri,
        "error" to row.error, "historyId" to row.historyId, "createdAt" to row.createdAt, "batchId" to row.batchId,
        "probe_errorCode" to row.probe?.errorCode, "probe_error" to row.probe?.error,
        "probe_hasGainMap" to row.probe?.hasGainMap, "probe_container" to row.probe?.container,
        "probe_width" to row.probe?.width, "probe_height" to row.probe?.height,
        "probe_gainmapWidth" to row.probe?.gainmapWidth, "probe_gainmapHeight" to row.probe?.gainmapHeight,
        "probe_hasExif" to row.probe?.hasExif, "probe_maxContentBoost" to row.probe?.maxContentBoost,
        "probe_hdrCapacityMax" to row.probe?.hdrCapacityMax,
        "result_errorCode" to row.result?.errorCode, "result_error" to row.result?.error,
        "result_inputHadGainMap" to row.result?.inputHadGainMap, "result_width" to row.result?.width,
        "result_height" to row.result?.height, "result_gainmapWidth" to row.result?.gainmapWidth,
        "result_gainmapHeight" to row.result?.gainmapHeight, "result_inputBytes" to row.result?.inputBytes,
        "result_outputBytes" to row.result?.outputBytes, "result_durationMs" to row.result?.durationMs,
        "result_hasGainMap" to row.result?.hasGainMap, "result_hasExif" to row.result?.hasExif,
        "result_maxContentBoost" to row.result?.maxContentBoost)

    private fun values(vararg fields: Pair<String, Any?>) = ContentValues().apply {
        fields.forEach { (name, value) -> when (value) {
            null -> putNull(name)
            is String -> put(name, value)
            is Boolean -> put(name, value)
            is Int -> put(name, value)
            is Long -> put(name, value)
            is Float -> put(name, value)
            is Double -> put(name, value)
            else -> error("Unsupported fixture column $name")
        } }
    }
}
